export class PublicApi {
  /** P-1, P-2: Public program catalog (anonymous reads). */
  readonly programs: PublicProgramsApi;
  /** Public mentors directory — active CRM mentors, safe projection (anonymous reads). */
  readonly mentors: PublicMentorsApi;
  /** P-3: Public lead capture from site forms (anonymous write, captcha-gated). */
  readonly leads: PublicLeadsApi;
  /** P-5: Public coupon validation for pricing/checkout (anonymous write, captcha-gated). */
  readonly coupons: PublicCouponsApi;
  /** P-6: Self-service student registration (anonymous → issues session). */
  readonly auth: PublicAuthApi;
  /**
   * P-7, P-8, P-9: Self-service enrollment funnel (requires session from register()).
   * All methods are own-scoped (student acts only on their own order).
   */
  readonly enroll: PublicEnrollApi;
  /** P-4: Book-Free-Slot intake (anonymous write, reuses P2 /public/bookings). */
  readonly bookings: PublicBookingsApi;
  /** Pay-link flow (lifecycle-redesign): token-authorized Razorpay checkout — no session. */
  readonly payLink: PublicPayLinkApi;
  /**
   * Phase 9 Completion (docs/plans/phase-9-completion.md T14) — headless CMS public
   * reads (nested: `content.blog` / `.testimonials` / `.partners` / `.facultyBios` /
   * `.pages` / `.kbArticles`), newsletter subscribe/unsubscribe, contact form, career
   * apply, landing-page render, lead-form config read, referral redeem.
   */
  readonly content: PublicContentApi;
  /**
   * Phase-10 page builder (docs/specs/phase-10-page-builder.md) — all 8 sitewide
   * SiteSetting values (nav/footer/SEO/contact/stats) in one cacheable call. Page-builder
   * pages themselves are read via `content.pages.getBySlug()` (already resolves
   * `live_collection_ref` blocks server-side when `isBuilderManaged=true`).
   */
  readonly siteSettings: PublicSiteSettingsApi;
  readonly newsletter: PublicNewsletterApi;
  readonly contact: PublicContactApi;
  readonly careers: PublicCareersApi;
  readonly landingPages: PublicLandingPagesApi;
  readonly leadForms: PublicLeadFormsApi;
  readonly referrals: PublicReferralsApi;
  /**
   * Phase 9 Completion follow-up (docs T30) — promoted from backend-local schemas.
   * `seo`/`bundles`: per-city SEO landing pages + track/bundle pricing (growth
   * public surface). `search`: CLIENT-SIDE composition over public.programs +
   * public.content.blog — there is no dedicated backend search route (see
   * @repo/types public/search.schemas.ts file header).
   */
  readonly seo: PublicSeoApi;
  readonly bundles: PublicBundlesApi;
  readonly search: PublicSearchApi;
  /**
   * Student onboarding form (onboarding.stimuliiq.com). The question set is authored in the
   * CRM, so `onboarding.getForm()` is what the page renders from — the client bundle
   * hardcodes no questions. File answers (the payment receipt) go through
   * `onboarding.getUploadUrl()` first; only the returned `storageKey` is ever submitted.
   */
  readonly onboarding: PublicOnboardingApi;

  constructor(client: ApiClient) {
    this.programs = new PublicProgramsApi(client);
    this.mentors = new PublicMentorsApi(client);
    this.leads = new PublicLeadsApi(client);
    this.coupons = new PublicCouponsApi(client);
    this.auth = new PublicAuthApi(client);
    this.enroll = new PublicEnrollApi(client);
    this.bookings = new PublicBookingsApi(client);
    this.payLink = new PublicPayLinkApi(client);
    this.content = new PublicContentApi(client);
    this.siteSettings = new PublicSiteSettingsApi(client);
    this.newsletter = new PublicNewsletterApi(client);
    this.contact = new PublicContactApi(client);
    this.careers = new PublicCareersApi(client);
    this.landingPages = new PublicLandingPagesApi(client);
    this.leadForms = new PublicLeadFormsApi(client);
    this.referrals = new PublicReferralsApi(client);
    this.seo = new PublicSeoApi(client);
    this.bundles = new PublicBundlesApi(client);
    this.search = new PublicSearchApi(client);
    this.onboarding = new PublicOnboardingApi(client);
  }
}

