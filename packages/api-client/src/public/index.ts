// Public API namespace — Phase 5, Wave 2 (docs/plans/phase-5.md task #2).
//
// Exposed on the SDK as `client.public.*`. Each resource API is a thin typed
// wrapper over the shared ApiClient http core (envelope unwrap + error handling).
// Anonymous endpoints do NOT set X-CSRF-Token or require cookieAuth.
// Self-service endpoints (enroll.*) require the session issued by register().
//
// Namespace layout:
//   client.public.programs.*  — P-1 (list), P-2 (getBySlug)
//   client.public.leads.*     — P-3 (capture)
//   client.public.coupons.*   — P-5 (validate)
//   client.public.auth.*      — P-6 (register)
//   client.public.enroll.*    — P-7 (createOrder), P-8 (checkout), P-9 (verify)
//   client.public.bookings.*  — P-4 (createPublic — reused from crm/bookings)
//
// P-4 (POST /public/bookings) is on `client.crm.bookings.createPublic()` (P2 reuse).
// It is also aliased here as `client.public.bookings.create()` for convenience in the
// web app so developers don't need to reach into crm.bookings for a public write.
//
// Security contracts:
//   - client.public.programs.*: unauthenticated GETs. No credentials headers.
//   - client.public.leads.capture(): no auth; captchaToken in body; rate-limited.
//   - client.public.coupons.validate(): no auth; captchaToken in body; rate-limited.
//   - client.public.auth.register(): no auth; captchaToken in body; issues session.
//   - client.public.enroll.*: cookieAuth (session from register()); own-scoped.
//     Idempotency-Key generated by default (crypto.randomUUID()) or caller-supplied.
//     Client MUST supply the same idempotencyKey on retries (not a new one).

